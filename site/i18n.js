const STORAGE_KEY = "podsync_promo_lang";

function detectInitialLang() {
  const params = new URLSearchParams(window.location.search);
  const queryLang = params.get("lang");
  if (queryLang && TRANSLATIONS[queryLang]) {
    return queryLang;
  }

  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && TRANSLATIONS[saved]) {
      return saved;
    }
  } catch {
    // Ignore storage access errors
  }

  const navLang = (navigator.language || "en").toLowerCase().split("-")[0];
  if (TRANSLATIONS[navLang]) {
    return navLang;
  }

  return "en";
}

function applyLanguage(lang) {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  document.documentElement.lang = lang;
  document.title = dict.page_title;

  for (const el of document.querySelectorAll("[data-i18n]")) {
    const key = el.getAttribute("data-i18n");
    if (key && dict[key]) {
      el.textContent = dict[key];
    }
  }

  const select = document.getElementById("lang-select");
  if (select) {
    select.value = lang;
  }

  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    // Ignore storage access errors
  }
}

document.addEventListener("DOMContentLoaded", () => {
  let currentLang = detectInitialLang();
  applyLanguage(currentLang);

  const select = document.getElementById("lang-select");
  if (select) {
    select.addEventListener("change", (event) => {
      const next = event.target.value;
      if (TRANSLATIONS[next]) {
        currentLang = next;
        applyLanguage(next);
      }
    });
  }

  for (const btn of document.querySelectorAll(".copy-btn")) {
    btn.addEventListener("click", async () => {
      const targetId = btn.getAttribute("data-copy-target");
      const codeEl = targetId ? document.getElementById(targetId) : null;
      if (!codeEl) return;

      const text = codeEl.textContent || "";
      try {
        await navigator.clipboard.writeText(text);
        const dict = TRANSLATIONS[currentLang] || TRANSLATIONS.en;
        btn.textContent = dict.btn_copied;
        setTimeout(() => {
          btn.textContent = dict.btn_copy;
        }, 1800);
      } catch {
        // Fallback ignored if clipboard permission denied
      }
    });
  }
});
